def classify(text: str) -> Rule | None:
    t = text.lower()
    for rule in RULES:
        for kw in rule.keywords:
            if kw in t:
                return rule
    return None


def check(text: str) -> tuple:
    rule = classify(text)
    if rule is None:
        return True, "", None
    return False, rule.response, rule.id


def refusal_message(rule_id: int) -> str:
    for r in RULES:
        if r.id == rule_id:
            return r.response
    return "Не могу помочь с этим."
